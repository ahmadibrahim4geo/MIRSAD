"""Reproduce the independent scientific kernel from the reviewed MIT toolbox.

Development-time extraction only: the distributed application never imports or
locates ArcGIS/toolbox files. Only the pure calculation dependency closure and
an explicit list of constants are copied. No toolbox code is executed here.
"""
import ast
import builtins
import hashlib
import symtable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT.parent/"Toolboxes/MIRSAD_Climate_Atlas_Generator_10_8.pyt"
text = source.read_text(encoding="utf-8-sig")
tree = ast.parse(text)
functions = {n.name:n for n in tree.body if isinstance(n,ast.FunctionDef)}
tables = {t.get_name():t for t in symtable.symtable(text,str(source),"exec").get_children()}
selected,external,todo = set(),set(),["compute_point_fields"]
while todo:
    name = todo.pop()
    if name in selected: continue
    selected.add(name)
    scopes = [tables[name]]
    while scopes:
        scope = scopes.pop(); scopes.extend(scope.get_children())
        for symbol in scope.get_symbols():
            if symbol.is_global() and symbol.is_referenced() and symbol.get_name() not in dir(builtins):
                dependency = symbol.get_name()
                if dependency in functions: todo.append(dependency)
                else: external.add(dependency)
constants = {"SEASONS","MISSING_SENTINELS","MONTH_NAMES_EN","BASELINE_YEARS",
             "BASELINE_MIN_YEARS","RECENT_WINDOW","RECENT_MIN_YEARS","TREND_MIN_YEARS"}
if external - constants - {"math","calendar"}:
    raise RuntimeError("Unreviewed scientific dependencies: "+str(external))
nodes = [n for n in tree.body if isinstance(n,ast.Assign) and
         any(isinstance(t,ast.Name) and t.id in constants for t in n.targets)]
nodes += [n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name in selected]
header = ('"""Reviewed legacy calculations. Generated by scripts/vendor_science.py.\n'
          'MIT: Ahmad Ibrahim / MIRSAD. Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()+'\n'
          'This module has no ArcGIS dependency. Do not hand-edit; add adapters/tests separately.\n"""\n'
          'import math\nimport calendar\n\n')
(ROOT/"src/mirsad_desktop/science.py").write_text(header+"\n\n".join(ast.unparse(n) for n in nodes)+"\n",encoding="utf-8")
print("Vendored",len(selected),"pure scientific functions")
pipeline=ROOT.parent/"mirsad_core/hybrid_pipeline.py"
(ROOT/"src/mirsad_desktop/hybrid_pipeline.py").write_bytes(pipeline.read_bytes())
print("Vendored shared Python 2/3 Hybrid source pipeline:",hashlib.sha256(pipeline.read_bytes()).hexdigest())
sources=ROOT.parent/"mirsad_core/climate_sources.py"
(ROOT/"src/mirsad_desktop/climate_sources.py").write_bytes(sources.read_bytes())
print("Vendored shared provider policies:",hashlib.sha256(sources.read_bytes()).hexdigest())
for name in ("climate_products.py","remote_grid.py","protected_sources.py","daily_climate.py"):
    shared=ROOT.parent/"mirsad_core"/name
    (ROOT/"src/mirsad_desktop"/name).write_bytes(shared.read_bytes())
    print("Vendored shared product adapter:",name,hashlib.sha256(shared.read_bytes()).hexdigest())
